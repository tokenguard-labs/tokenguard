// Copies the sidebar's browser libraries from node_modules into media/vendor/.
// Runs before every `npm run compile`. The output is committed (like out/) so the
// extension still works on machines without npm (see scripts/setup.sh).
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const modules = join(root, 'node_modules');
const vendor = join(root, 'media', 'vendor');

// [package, file inside the package, published name in media/vendor]
const FILES = [
    ['marked', 'lib/marked.umd.js', 'marked.umd.js'],
    ['marked', 'LICENSE', 'licenses/marked.LICENSE'],
    ['dompurify', 'dist/purify.min.js', 'purify.min.js'],
    ['dompurify', 'LICENSE', 'licenses/dompurify.LICENSE'],
    ['@highlightjs/cdn-assets', 'highlight.min.js', 'highlight.min.js'],
    ['@highlightjs/cdn-assets', 'styles/github.min.css', 'hljs-light.min.css'],
    ['@highlightjs/cdn-assets', 'styles/github-dark.min.css', 'hljs-dark.min.css'],
    ['@highlightjs/cdn-assets', 'LICENSE', 'licenses/highlight.js.LICENSE'],
];

const versions = new Map();
for (const [pkg, from, to] of FILES) {
    const dest = join(vendor, to);
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(join(modules, pkg, from), dest);
    if (!versions.has(pkg)) {
        versions.set(pkg, JSON.parse(readFileSync(join(modules, pkg, 'package.json'), 'utf8')).version);
    }
}

writeFileSync(join(vendor, 'README.md'), [
    '# media/vendor',
    '',
    'Generated by `scripts/copy-vendor.mjs` (runs on `npm run compile`). Do not edit by hand:',
    'bump the version in `package.json`, run `npm install && npm run compile`, and commit the result.',
    '',
    ...[...versions].map(([pkg, version]) => `- ${pkg} ${version}`),
    '',
].join('\n'));

console.log(`vendor: ${[...versions].map(([p, v]) => `${p}@${v}`).join(', ')}`);
